$src       = Join-Path $PSScriptRoot 'FFmpeg_Converter_run_win_v18.ps1'
$scriptPs1 = Join-Path $PSScriptRoot 'FFmpeg_Converter_script.ps1'
$out       = Join-Path $PSScriptRoot '_VideoConverter_v18.exe'
$ps2exePs  = Join-Path $PSScriptRoot '..\tools\ps2exe.ps1'
$tmpSrc    = Join-Path $PSScriptRoot '_build_tmp.ps1'

# Общие константы (SHA-пин ps2exe + версия) и проверка — один источник на оба build-скрипта.
. (Join-Path $PSScriptRoot '../tools/_build_common.ps1')
Assert-Ps2Exe $ps2exePs

# --- Встраиваем script.ps1 в run_win.ps1 ---
Write-Host "Embedding FFmpeg_Converter_script.ps1..."
$scriptContent = Remove-PsComments ([System.IO.File]::ReadAllText($scriptPs1, [System.Text.Encoding]::UTF8))

# Модуль удалённого бэкенда встраиваем в ту же строку: EXE обязан быть
# самодостаточным, а рядом с EXE файла remote_client.ps1 нет, и удалённый счёт молча
# остался бы недоступным. script.ps1 подключает модуль только тогда, когда функции ещё
# не объявлены (Get-Command Set-RemoteActive) — здесь они уже вклеены, и дот-сорсинг
# не выполняется вовсе.
$remotePs1 = Join-Path $PSScriptRoot 'remote_client.ps1'
if (Test-Path -LiteralPath $remotePs1) {
    Write-Host 'Embedding remote_client.ps1...'
    $remoteContent = Remove-PsComments ([System.IO.File]::ReadAllText($remotePs1, [System.Text.Encoding]::UTF8))
    $scriptContent = $remoteContent + "`n" + $scriptContent
}

# Встраиваемый текст живёт внутри here-string @'…'@. Строка, начинающаяся с '@ (после
# необязательных пробелов), закрыла бы её досрочно: EXE собрался бы, CI smoke-build
# остался бы зелёным, а при запуске пользователь получил бы parse error. Проверяем до
# сборки — здесь это три строки, а в готовом EXE это уже не диагностируется.
$_badTerm = ($scriptContent -split "`r?`n") | Where-Object { $_ -match "^\s*'@" }
if ($_badTerm) {
    Write-Host "FAIL: встраиваемый текст содержит строку, закрывающую here-string: $($_badTerm[0])"
    exit 1
}

$embedBlock = @"

# === EMBEDDED SCRIPT (auto-generated by build_exe.ps1) ===
`$script:_embeddedScript = @'
$scriptContent
'@
# === END EMBEDDED SCRIPT ===
"@

# Комментарии снимаются со ВСЕХ трёх исходников этого EXE: и со встраиваемых, и с
# самого GUI. Текст комментариев входит в сумму признаков, по которой антивирус
# выносит вердикт — измерено в этом репозитории (docs/knowledge-base.md), см.
# Remove-PsComments в tools/_build_common.ps1. В репозитории врезки остаются.
$mainContent = Remove-PsComments ([System.IO.File]::ReadAllText($src, [System.Text.Encoding]::UTF8))
# Вставляем встроенный скрипт ПЕРЕД первой строкой кода (после комментариев)
$combined = $embedBlock + "`n" + $mainContent
[System.IO.File]::WriteAllText($tmpSrc, $combined, [System.Text.Encoding]::UTF8)
Write-Host "Combined file: $([math]::Round((Get-Item -LiteralPath $tmpSrc).Length / 1KB)) KB"

Write-Host "Loading ps2exe function..."
. $ps2exePs

# Удаляем прежний EXE ДО сборки: иначе при падении Invoke-ps2exe остался бы старый
# файл и Test-Path ниже дал бы ложный SUCCESS.
Remove-Item -LiteralPath $out -Force -ErrorAction SilentlyContinue

Write-Host "Running Invoke-ps2exe..."
$ErrorActionPreference = 'Stop'
try {
    Invoke-ps2exe `
        -inputFile  $tmpSrc `
        -outputFile $out `
        -noConsole `
        -STA `
        -x64 `
        -title   "Video Converter (ffmpeg) v18" `
        -version $script:BuildVersion
} catch {
    Write-Host "FAIL: $_"
    Remove-Item -LiteralPath $tmpSrc -Force -ErrorAction SilentlyContinue
    exit 1
}

Remove-Item -LiteralPath $tmpSrc -Force -ErrorAction SilentlyContinue

if (Test-Path -LiteralPath $out) {
    $size = [math]::Round((Get-Item -LiteralPath $out).Length / 1KB)
    Write-Host "SUCCESS: $out ($size KB)"
    Write-ExeChecksum $out
} else {
    Write-Host "FAILED: EXE not created"
    exit 1
}
